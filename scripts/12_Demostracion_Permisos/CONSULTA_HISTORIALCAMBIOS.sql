USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

DECLARE @TOTALREAL INT;

SELECT @TOTALREAL = COUNT(*)
FROM DBO.AUDITORIASISTEMA;

EXECUTE AS USER = N'USERAUDITOR'; -- noqa: PRS
SELECT
    USER_NAME() AS IDENTIDAD,
    IS_MEMBER(N'AUDITOR') AS ESAUDITOR,
    @TOTALREAL AS FILAS_EN_LA_TABLA,
    COUNT(*) AS FILAS_QUE_VE_EL_USUARIO
FROM DBO.FN_CONSULTARHISTORIALCAMBIOS();
SELECT TOP 5
    ID_AUDITORIA,
    TABLA_AFECTADA,
    LLAVE_PRIMARIA,
    ID_OPERACION,
    CAMPO_MODIFICADO,
    VALOR_ANTERIOR,
    VALOR_NUEVO,
    USUARIO,
    FECHA_HORA
FROM DBO.FN_CONSULTARHISTORIALCAMBIOS()
ORDER BY ID_AUDITORIA;
REVERT;

EXECUTE AS USER = N'USERDBA'; -- noqa: PRS
SELECT
    USER_NAME() AS IDENTIDAD,
    IS_MEMBER(N'DBA') AS ESDBA,
    @TOTALREAL AS FILAS_EN_LA_TABLA,
    COUNT(*) AS FILAS_QUE_VE_EL_USUARIO
FROM DBO.FN_CONSULTARHISTORIALCAMBIOS();
SELECT TOP 5
    ID_AUDITORIA,
    TABLA_AFECTADA,
    LLAVE_PRIMARIA,
    ID_OPERACION,
    CAMPO_MODIFICADO,
    VALOR_ANTERIOR,
    VALOR_NUEVO,
    USUARIO,
    FECHA_HORA
FROM DBO.FN_CONSULTARHISTORIALCAMBIOS()
ORDER BY ID_AUDITORIA;
REVERT;

EXECUTE AS USER = N'USERADMINISTRADOR'; -- noqa: PRS

BEGIN TRY
    SELECT
        USER_NAME() AS IDENTIDAD,
        COUNT(*) AS FILAS_QUE_VE_EL_USUARIO
    FROM DBO.FN_CONSULTARHISTORIALCAMBIOS();
END TRY
BEGIN CATCH
    SELECT
        USER_NAME() AS IDENTIDAD,
        'ACCESO DENEGADO CORRECTAMENTE' AS ESTADO_PERMISO,
        ERROR_MESSAGE() AS MENSAJE_ERROR;
END CATCH;

REVERT;

EXECUTE AS USER = N'USEROPERATIVO'; -- noqa: PRS

BEGIN TRY
    SELECT
        USER_NAME() AS IDENTIDAD,
        COUNT(*) AS FILAS_QUE_VE_EL_USUARIO
    FROM DBO.FN_CONSULTARHISTORIALCAMBIOS();
END TRY
BEGIN CATCH
    SELECT
        USER_NAME() AS IDENTIDAD,
        'ACCESO DENEGADO CORRECTAMENTE' AS ESTADO_PERMISO,
        ERROR_MESSAGE() AS MENSAJE_ERROR;
END CATCH;
REVERT;
GO

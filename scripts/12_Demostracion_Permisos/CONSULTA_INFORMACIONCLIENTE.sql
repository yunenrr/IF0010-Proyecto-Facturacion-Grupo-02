USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

DECLARE @CEDULA VARCHAR(20);
 
SELECT @CEDULA = CEDULA_CLIENTE
FROM DBO.CLIENTE
ORDER BY ID_CLIENTE;
 
EXECUTE AS USER = N'USERADMINISTRADOR'; -- noqa: PRS
 
BEGIN TRY
    SELECT
        ID_CLIENTE,
        CEDULA_CLIENTE,
        TIPO_IDENTIFICACION,
        NOMBRE,
        PROVINCIA,
        CANTON,
        DISTRITO,
        SENAS_ADICIONALES,
        FECHA_REGISTRO,
        TELEFONO,
        CORREO,
        USER_NAME() AS IDENTIDAD
    FROM DBO.FN_INFORMACIONCLIENTES(@CEDULA);
END TRY
BEGIN CATCH
    SELECT
        USER_NAME() AS IDENTIDAD,
        'ACCESO DENEGADO' AS ESTADO_PERMISO,
        ERROR_MESSAGE() AS MENSAJE_ERROR;
END CATCH;
 
REVERT;


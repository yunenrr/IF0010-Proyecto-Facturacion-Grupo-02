USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO
IF EXISTS (SELECT 1 FROM SYS.OBJECTS WHERE NAME = 'PR_REGISTRARFACTURACONDETALLES' AND TYPE = 'P')
    BEGIN
        DROP PROCEDURE DBO.PR_REGISTRARFACTURACONDETALLES;
    END;
GO

CREATE PROCEDURE DBO.PR_REGISTRARFACTURACONDETALLES
    @ID_EMPRESA INT,
    @ID_CLIENTE INT,
    @ID_TIPO_DOCUMENTO INT,
    @CODIGO_DIVISA CHAR(3),
    @ID_ESTADO INT,
    @LINEAS NVARCHAR(MAX),
    @CODIGO_FACTURA INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        IF NOT EXISTS (SELECT 1 FROM DBO.EMPRESA_EMISORA WHERE ID_EMPRESA = @ID_EMPRESA AND ACTIVA = 1)
            BEGIN
                THROW 50160, 'La empresa emisora no existe o no esta activa.', 1;
            END;

        IF NOT EXISTS (SELECT 1 FROM DBO.CLIENTE WHERE ID_CLIENTE = @ID_CLIENTE)
            BEGIN
                THROW 50161, 'El cliente especificado no existe.', 1;
            END;

        IF NOT EXISTS (SELECT 1 FROM DBO.TIPO_DOCUMENTO WHERE ID_TIPO_DOCUMENTO = @ID_TIPO_DOCUMENTO)
            BEGIN
                THROW 50162, 'El tipo de documento no existe.', 1;
            END;

        IF NOT EXISTS (SELECT 1 FROM DBO.DIVISA WHERE CODIGO_DIVISA = @CODIGO_DIVISA)
            BEGIN
                THROW 50163, 'La divisa especificada no existe.', 1;
            END;

        IF NOT EXISTS (SELECT 1 FROM DBO.ESTADO_FACTURA WHERE ID_ESTADO = @ID_ESTADO)
            BEGIN
                THROW 50164, 'El estado especificado no existe.', 1;
            END;

        IF @LINEAS IS NULL OR ISJSON(@LINEAS) = 0
            BEGIN
                THROW 50165, 'Las lineas de la factura no son validas.', 1;
            END;

        CREATE TABLE #LINEAS (
            NUMERO_LINEA INT,
            CODIGO_PRODUCTO INT,
            DESCRIPCION VARCHAR(255),
            CANTIDAD DECIMAL(12, 2),
            PRECIO_UNITARIO DECIMAL(18, 2),
            PORCENTAJE_DESCUENTO DECIMAL(5, 2),
            PORCENTAJE_IMPUESTO DECIMAL(5, 2),
            STOCK_ACTUAL INT,
            SUBTOTAL_LINEA DECIMAL(18, 2),
            MONTO_DESCUENTO DECIMAL(18, 2),
            MONTO_IMPUESTO DECIMAL(18, 2),
            MONTO_TOTAL_LINEA DECIMAL(18, 2)
        );

        INSERT INTO #LINEAS (
            NUMERO_LINEA, CODIGO_PRODUCTO, DESCRIPCION, CANTIDAD,
            PRECIO_UNITARIO, PORCENTAJE_DESCUENTO, PORCENTAJE_IMPUESTO, STOCK_ACTUAL
        )
        SELECT
            ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS NUMERO_LINEA,
            P.CODIGO_ID AS CODIGO_PRODUCTO,
            P.DESCRIPCION AS DESCRIPCION,
            J.CANTIDAD AS CANTIDAD,
            P.PRECIO_UNITARIO AS PRECIO_UNITARIO,
            J.DESCUENTO AS PORCENTAJE_DESCUENTO,
            P.PORCENTAJE_IMPUESTO AS PORCENTAJE_IMPUESTO,
            P.STOCK_ACTUAL AS STOCK_ACTUAL
        FROM OPENJSON(@LINEAS) WITH (
            CODIGO INT '$.codigo',
            CANTIDAD DECIMAL(12, 2) '$.cantidad',
            DESCUENTO DECIMAL(5, 2) '$.descuento'
        ) AS J
        INNER JOIN DBO.PRODUCTO AS P
            ON J.CODIGO = P.CODIGO_ID
            AND P.ESTADO = 1;

        DECLARE @TOTALJSON INT;
        DECLARE @TOTALVALIDAS INT;

        SELECT @TOTALJSON = COUNT(*) FROM OPENJSON(@LINEAS);
        SELECT @TOTALVALIDAS = COUNT(*) FROM #LINEAS;

        IF @TOTALJSON = 0 OR @TOTALJSON <> @TOTALVALIDAS
            BEGIN
                THROW 50166, 'Hay productos inexistentes o inactivos, o la factura no tiene lineas.', 1;
            END;

        IF EXISTS (
            SELECT 1 FROM #LINEAS
            WHERE CANTIDAD <= 0 OR PORCENTAJE_DESCUENTO NOT BETWEEN 0 AND 100
        )
            BEGIN
                THROW 50167, 'Cantidad o descuento invalidos en alguna linea.', 1;
            END;

        IF EXISTS (SELECT 1 FROM #LINEAS WHERE CANTIDAD > STOCK_ACTUAL)
            BEGIN
                THROW 50168, 'Stock insuficiente para alguno de los productos.', 1;
            END;

        UPDATE #LINEAS
        SET
            SUBTOTAL_LINEA = ROUND(CANTIDAD * PRECIO_UNITARIO, 2),
            MONTO_DESCUENTO = ROUND(CANTIDAD * PRECIO_UNITARIO * PORCENTAJE_DESCUENTO / 100.00, 2);

        UPDATE #LINEAS
        SET
            MONTO_IMPUESTO = ROUND((SUBTOTAL_LINEA - MONTO_DESCUENTO) * PORCENTAJE_IMPUESTO / 100.00, 2);

        UPDATE #LINEAS
        SET MONTO_TOTAL_LINEA = SUBTOTAL_LINEA - MONTO_DESCUENTO + MONTO_IMPUESTO;

        DECLARE @FECHA DATETIME2 = SYSDATETIME();
        DECLARE @CLAVE VARCHAR(100);

        SET @CLAVE = DBO.FN_GENERARCLAVECOMPROBANTE(@FECHA, @ID_TIPO_DOCUMENTO);

        IF EXISTS (SELECT 1 FROM DBO.FACTURA WHERE IDENTIFICADOR_COMPROBANTE = @CLAVE)
            BEGIN
                THROW 50169, 'Ya existe un comprobante con ese identificador. Intente de nuevo.', 1;
            END;

        SELECT @CODIGO_FACTURA = ISNULL(MAX(CODIGO_FACTURA), 0) + 1
        FROM DBO.FACTURA WITH (UPDLOCK, HOLDLOCK);

        INSERT INTO DBO.FACTURA (
            CODIGO_FACTURA, IDENTIFICADOR_COMPROBANTE, ID_EMPRESA, ID_CLIENTE,
            ID_TIPO_DOCUMENTO, CODIGO_DIVISA, ID_ESTADO, FECHA_EMISION,
            SUBTOTAL, TOTAL_DESCUENTOS, TOTAL_IMPUESTOS, MONTO_TOTAL
        )
        SELECT
            @CODIGO_FACTURA, @CLAVE, @ID_EMPRESA, @ID_CLIENTE,
            @ID_TIPO_DOCUMENTO, @CODIGO_DIVISA, @ID_ESTADO, @FECHA,
            SUM(SUBTOTAL_LINEA), SUM(MONTO_DESCUENTO),
            SUM(MONTO_IMPUESTO), SUM(MONTO_TOTAL_LINEA)
        FROM #LINEAS;

        INSERT INTO DBO.DETALLE_FACTURA (
            CODIGO_FACTURA, CODIGO_PRODUCTO, NUMERO_LINEA, DESCRIPCION,
            CANTIDAD, PRECIO_UNITARIO, PORCENTAJE_DESCUENTO, PORCENTAJE_IMPUESTO,
            SUBTOTAL_LINEA, MONTO_DESCUENTO, MONTO_IMPUESTO, MONTO_TOTAL_LINEA
        )
        SELECT
            @CODIGO_FACTURA, CODIGO_PRODUCTO, NUMERO_LINEA, DESCRIPCION,
            CANTIDAD, PRECIO_UNITARIO, PORCENTAJE_DESCUENTO, PORCENTAJE_IMPUESTO,
            SUBTOTAL_LINEA, MONTO_DESCUENTO, MONTO_IMPUESTO, MONTO_TOTAL_LINEA
        FROM #LINEAS;

        DROP TABLE #LINEAS;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            BEGIN
                ROLLBACK TRANSACTION;
            END;

        THROW;
    END CATCH;
END;
GO

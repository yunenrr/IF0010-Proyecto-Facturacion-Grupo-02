GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'VW_RESUMENDIARIOFACTURAS'
            AND TYPE = 'V'
    )
    BEGIN
        DROP VIEW DBO.VW_RESUMENDIARIOFACTURAS;
    END;
GO

CREATE VIEW DBO.VW_RESUMENDIARIOFACTURAS
AS
SELECT
    E.RAZON_SOCIAL AS NOMBREEMPRESA,
    TD.DESCRIPCION_TIPO_DOCUMENTO AS TIPODOCUMENTO,
    CONVERT(DATE, F.FECHA_EMISION) AS FECHAEMISION,
    COUNT(*) AS CANTIDADFACTURAS,
    SUM(F.SUBTOTAL) AS SUBTOTALACUMULADO,
    SUM(F.TOTAL_DESCUENTOS) AS TOTALDESCUENTOS,
    SUM(F.TOTAL_IMPUESTOS) AS TOTALIMPUESTOS,
    SUM(F.MONTO_TOTAL) AS MONTOTOTALFACTURADO
FROM DBO.FACTURA AS F
INNER JOIN DBO.EMPRESA_EMISORA AS E
    ON F.ID_EMPRESA = E.ID_EMPRESA
INNER JOIN DBO.TIPO_DOCUMENTO AS TD
    ON F.ID_TIPO_DOCUMENTO = TD.ID_TIPO_DOCUMENTO
GROUP BY
    E.RAZON_SOCIAL,
    TD.DESCRIPCION_TIPO_DOCUMENTO,
    CONVERT(DATE, F.FECHA_EMISION);
GO

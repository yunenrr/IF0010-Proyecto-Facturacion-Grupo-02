USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF EXISTS (SELECT 1 FROM SYS.OBJECTS WHERE NAME = 'VW_LISTADOFACTURAS' AND TYPE = 'V')
    BEGIN
        DROP VIEW DBO.VW_LISTADOFACTURAS;
    END;
GO

CREATE VIEW DBO.VW_LISTADOFACTURAS
AS
SELECT
    F.CODIGO_FACTURA,
    F.IDENTIFICADOR_COMPROBANTE,
    F.FECHA_EMISION,
    E.NOMBRE_COMERCIAL AS EMPRESA,
    C.CEDULA,
    COALESCE(
        CJ.NOMBRE_COMERCIAL,
        CONCAT_WS(' ', CF.NOMBRE, CF.PRIMER_APELLIDO, CF.SEGUNDO_APELLIDO)
    ) AS CLIENTE,
    TD.DESCRIPCION_TIPO_DOCUMENTO AS TIPO_DOCUMENTO,
    F.CODIGO_DIVISA,
    EF.ESTADO,
    F.SUBTOTAL,
    F.TOTAL_DESCUENTOS,
    F.TOTAL_IMPUESTOS,
    F.MONTO_TOTAL
FROM DBO.FACTURA AS F
INNER JOIN DBO.EMPRESA_EMISORA AS E
    ON F.ID_EMPRESA = E.ID_EMPRESA
INNER JOIN DBO.CLIENTE AS C
    ON F.ID_CLIENTE = C.ID_CLIENTE
LEFT JOIN DBO.CLIENTE_FISICO AS CF
    ON C.ID_CLIENTE = CF.ID_CLIENTE
LEFT JOIN DBO.CLIENTE_JURIDICO AS CJ
    ON C.ID_CLIENTE = CJ.ID_CLIENTE
INNER JOIN DBO.TIPO_DOCUMENTO AS TD
    ON F.ID_TIPO_DOCUMENTO = TD.ID_TIPO_DOCUMENTO
INNER JOIN DBO.ESTADO_FACTURA AS EF
    ON F.ID_ESTADO = EF.ID_ESTADO;
GO

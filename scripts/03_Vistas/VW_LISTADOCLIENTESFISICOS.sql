GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'VW_LISTADOCLIENTESFISICOS'
            AND TYPE = 'V'
    )
    BEGIN
        DROP VIEW DBO.VW_LISTADOCLIENTESFISICOS;
    END;
GO

CREATE VIEW DBO.VW_LISTADOCLIENTESFISICOS
AS
SELECT
    C.ID_CLIENTE,
    C.CEDULA,
    CF.NOMBRE,
    CF.PRIMER_APELLIDO,
    CF.SEGUNDO_APELLIDO,
    CASE
        WHEN
            IS_MEMBER(N'ADMINISTRADOR') = 1
            OR IS_MEMBER(N'DBA') = 1
            THEN C.TELEFONO
        ELSE CONCAT('XXXX-', RIGHT(C.TELEFONO, 4))
    END AS TELEFONO,
    CASE
        WHEN
            IS_MEMBER(N'ADMINISTRADOR') = 1
            OR IS_MEMBER(N'DBA') = 1
            THEN C.CORREO
        ELSE CONCAT(LEFT(C.CORREO, 1), '***@***')
    END AS CORREO
FROM DBO.CLIENTE AS C
INNER JOIN DBO.CLIENTE_FISICO AS CF
    ON C.ID_CLIENTE = CF.ID_CLIENTE;
GO

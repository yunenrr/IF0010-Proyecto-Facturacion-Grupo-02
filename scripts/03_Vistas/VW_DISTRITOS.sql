-- La vista ahora expone el ID del cantón
IF EXISTS (SELECT 1 FROM SYS.OBJECTS WHERE NAME = 'VW_DISTRITOS' AND TYPE = 'V')
    BEGIN
        DROP VIEW DBO.VW_DISTRITOS;
    END;
GO

CREATE VIEW DBO.VW_DISTRITOS
AS
SELECT
    D.ID_DISTRITO,
    D.NOMBRE AS DISTRITO,
    C.ID_CANTON,
    C.NOMBRE AS CANTON,
    P.NOMBRE AS PROVINCIA
FROM DBO.DISTRITO AS D
INNER JOIN DBO.CANTON AS C
    ON D.ID_CANTON = C.ID_CANTON
INNER JOIN DBO.PROVINCIA AS P
    ON C.ID_PROVINCIA = P.ID_PROVINCIA;
GO

IF EXISTS (SELECT 1 FROM SYS.OBJECTS WHERE NAME = 'PR_REGISTRARDISTRITO' AND TYPE = 'P')
    BEGIN
        DROP PROCEDURE DBO.PR_REGISTRARDISTRITO;
    END;
GO

CREATE PROCEDURE DBO.PR_REGISTRARDISTRITO
    @ID_CANTON INT,
    @NOMBRE VARCHAR(100),
    @ID_DISTRITO INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        SET @NOMBRE = TRIM(@NOMBRE);

        IF NOT EXISTS (SELECT 1 FROM DBO.CANTON WHERE ID_CANTON = @ID_CANTON)
            BEGIN
                THROW 50170, 'El canton especificado no existe.', 1;
            END;

        IF @NOMBRE IS NULL OR LEN(@NOMBRE) < 3
            BEGIN
                THROW 50171, 'El nombre del distrito debe tener al menos 3 caracteres.', 1;
            END;

        SELECT @ID_DISTRITO = D.ID_DISTRITO
        FROM DBO.DISTRITO AS D
        WHERE
            D.ID_CANTON = @ID_CANTON
            AND D.NOMBRE COLLATE Latin1_General_CI_AI = @NOMBRE;

        IF @ID_DISTRITO IS NULL
            BEGIN
                SELECT @ID_DISTRITO = ISNULL(MAX(ID_DISTRITO), 0) + 1
                FROM DBO.DISTRITO WITH (UPDLOCK, HOLDLOCK);

                INSERT INTO DBO.DISTRITO (ID_DISTRITO, ID_CANTON, NOMBRE)
                VALUES (@ID_DISTRITO, @ID_CANTON, @NOMBRE);
            END;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            BEGIN
                ROLLBACK TRANSACTION;
            END;

        THROW;
    END CATCH;
END;
GO

GRANT SELECT ON DBO.VW_DISTRITOS TO ADMINISTRADOR;
GRANT SELECT ON DBO.VW_DISTRITOS TO DBA;
GRANT EXECUTE ON DBO.PR_REGISTRARDISTRITO TO ADMINISTRADOR;
GRANT EXECUTE ON DBO.PR_REGISTRARDISTRITO TO DBA;
GO

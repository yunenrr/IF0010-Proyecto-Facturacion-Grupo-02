USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'VW_LISTADOCLIENTES'
            AND TYPE = 'V'
    )
    BEGIN
        DROP VIEW DBO.VW_LISTADOCLIENTES;
    END;
GO

CREATE VIEW DBO.VW_LISTADOCLIENTES
AS
SELECT
    C.ID_CLIENTE,
    C.CEDULA,
    CASE
        WHEN CJ.ID_CLIENTE IS NOT NULL THEN 'JURIDICA'
        ELSE 'FISICA'
    END AS TIPO,
    COALESCE(
        CJ.NOMBRE_COMERCIAL,
        CONCAT_WS(' ', CF.NOMBRE, CF.PRIMER_APELLIDO, CF.SEGUNDO_APELLIDO)
    ) AS NOMBRE,
    CASE
        WHEN
            IS_MEMBER(N'ADMINISTRADOR') = 1
            OR IS_MEMBER(N'DBA') = 1
            THEN C.TELEFONO
        ELSE CONCAT('XXXX-', RIGHT(C.TELEFONO, 4))
    END AS TELEFONO,
    CASE
        WHEN
            IS_MEMBER(N'ADMINISTRADOR') = 1
            OR IS_MEMBER(N'DBA') = 1
            THEN C.CORREO
        ELSE CONCAT(LEFT(C.CORREO, 1), '***@***')
    END AS CORREO
FROM DBO.CLIENTE AS C
LEFT JOIN DBO.CLIENTE_FISICO AS CF
    ON C.ID_CLIENTE = CF.ID_CLIENTE
LEFT JOIN DBO.CLIENTE_JURIDICO AS CJ
    ON C.ID_CLIENTE = CJ.ID_CLIENTE;
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'VW_LISTADOPRODUCTOS'
            AND TYPE = 'V'
    )
    BEGIN
        DROP VIEW DBO.VW_LISTADOPRODUCTOS;
    END;
GO

CREATE VIEW DBO.VW_LISTADOPRODUCTOS
AS
SELECT
    P.CODIGO_ID,
    P.DESCRIPCION,
    P.PRECIO_UNITARIO,
    P.PORCENTAJE_IMPUESTO,
    P.STOCK_ACTUAL,
    P.STOCK_MINIMO,
    CASE WHEN P.ESTADO = 1 THEN 'Activo' ELSE 'Inactivo' END AS ESTADO
FROM DBO.PRODUCTO AS P;
GO

GRANT SELECT ON DBO.VW_LISTADOPRODUCTOS TO ADMINISTRADOR;
GRANT SELECT ON DBO.VW_LISTADOPRODUCTOS TO DBA;
GO

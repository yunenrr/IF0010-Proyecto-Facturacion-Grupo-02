USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'VW_DIRECCIONCLIENTE'
            AND TYPE = 'V'
    )
    BEGIN
        DROP VIEW DBO.VW_DIRECCIONCLIENTE;
    END;
GO

CREATE VIEW DBO.VW_DIRECCIONCLIENTE
AS
SELECT
    C.ID_CLIENTE,
    C.ID_DIRECCION
FROM DBO.CLIENTE AS C;
GO
USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'VW_CLIENTESRESUMEN'
            AND TYPE = 'V'
    )
    BEGIN
        DROP VIEW DBO.VW_CLIENTESRESUMEN;
    END;
GO

CREATE VIEW DBO.VW_CLIENTESRESUMEN AS
WITH CONTEOS AS (
    SELECT
        F.ID_CLIENTE,
        COUNT(*) AS TOTAL,
        SUM(
            CASE
                WHEN
                    F.FECHA_EMISION
                    >= DATEADD(MONTH, -6, SYSDATETIME())
                    THEN 1
                ELSE 0
            END
        ) AS RECIENTES
    FROM DBO.FACTURA AS F
    GROUP BY
        F.ID_CLIENTE
)

SELECT
    C.CEDULA AS CEDULA,
    COALESCE(
        CJ.RAZON_SOCIAL,
        CONCAT_WS(
            ' ',
            CF.NOMBRE,
            CF.PRIMER_APELLIDO,
            CF.SEGUNDO_APELLIDO
        )
    ) AS NOMBREORAZONSOCIAL,
    ISNULL(CO.TOTAL, 0) AS CANTIDADFACTURAS,
    CASE
        WHEN ISNULL(CO.RECIENTES, 0) > 5
            THEN 'Sí'
        ELSE 'No'
    END AS CLIENTEFRECUENTE
FROM DBO.CLIENTE AS C
LEFT JOIN DBO.CLIENTE_FISICO AS CF
    ON C.ID_CLIENTE = CF.ID_CLIENTE
LEFT JOIN DBO.CLIENTE_JURIDICO AS CJ
    ON C.ID_CLIENTE = CJ.ID_CLIENTE
LEFT JOIN CONTEOS AS CO
    ON C.ID_CLIENTE = CO.ID_CLIENTE;
GO

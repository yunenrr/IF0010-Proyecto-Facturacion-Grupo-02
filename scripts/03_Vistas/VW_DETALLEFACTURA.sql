USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF EXISTS (SELECT 1 FROM SYS.OBJECTS WHERE NAME = 'VW_DETALLEFACTURA' AND TYPE = 'V')
    BEGIN
        DROP VIEW DBO.VW_DETALLEFACTURA;
    END;
GO

CREATE VIEW DBO.VW_DETALLEFACTURA
AS
SELECT
    D.CODIGO_FACTURA,
    D.NUMERO_LINEA,
    D.CODIGO_PRODUCTO,
    D.DESCRIPCION,
    D.CANTIDAD,
    D.PRECIO_UNITARIO,
    D.PORCENTAJE_DESCUENTO,
    D.PORCENTAJE_IMPUESTO,
    D.SUBTOTAL_LINEA,
    D.MONTO_DESCUENTO,
    D.MONTO_IMPUESTO,
    D.MONTO_TOTAL_LINEA
FROM DBO.DETALLE_FACTURA AS D;
GO

IF EXISTS (SELECT 1 FROM SYS.OBJECTS WHERE NAME = 'VW_CATALOGOFACTURA' AND TYPE = 'V')
    BEGIN
        DROP VIEW DBO.VW_CATALOGOFACTURA;
    END;
GO

CREATE VIEW DBO.VW_CATALOGOFACTURA
AS
SELECT
    'EMPRESA' AS CATALOGO,
    CAST(E.ID_EMPRESA AS VARCHAR(20)) AS CODIGO,
    E.NOMBRE_COMERCIAL AS TEXTO
FROM DBO.EMPRESA_EMISORA AS E
WHERE E.ACTIVA = 1
UNION ALL
SELECT
    'TIPO' AS CATALOGO,
    CAST(T.ID_TIPO_DOCUMENTO AS VARCHAR(20)) AS CODIGO,
    T.DESCRIPCION_TIPO_DOCUMENTO AS TEXTO
FROM DBO.TIPO_DOCUMENTO AS T
UNION ALL
SELECT
    'DIVISA' AS CATALOGO,
    DV.CODIGO_DIVISA AS CODIGO,
    CONCAT(DV.CODIGO_DIVISA, ' - ', DV.NOMBRE) AS TEXTO
FROM DBO.DIVISA AS DV
UNION ALL
SELECT
    'ESTADO' AS CATALOGO,
    CAST(S.ID_ESTADO AS VARCHAR(20)) AS CODIGO,
    S.ESTADO AS TEXTO
FROM DBO.ESTADO_FACTURA AS S;
GO

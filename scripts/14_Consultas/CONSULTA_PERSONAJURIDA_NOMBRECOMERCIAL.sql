DECLARE @NOMBRE_COMERCIAL VARCHAR(100) = 'Empresa Comercial 14 S.A';

SELECT
    ID_EMPRESA AS ID_CLIENTE,
    CEDULA AS CEDULA_CLIENTE,
    NOMBRE_COMERCIAL,
    RAZON_SOCIAL,
    TELEFONO,
    CORREO,
    FECHA_CREACION AS FECHA_REGISTRO
FROM DBO.EMPRESAEMISORA
WHERE
    LEN(REPLACE(CEDULA, '-', '')) = 10
    AND NOMBRE_COMERCIAL LIKE '%' + @NOMBRE_COMERCIAL + '%';
GO

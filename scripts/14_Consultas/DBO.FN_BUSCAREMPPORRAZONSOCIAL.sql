IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_BUSCAREMPPORRAZONSOCIAL'
            AND TYPE = 'IF'
    )
    BEGIN
        DROP FUNCTION DBO.FN_BUSCAREMPPORRAZONSOCIAL;
    END;
GO

CREATE FUNCTION DBO.FN_BUSCAREMPPORRAZONSOCIAL(
    @RAZONSOCIAL VARCHAR(150)
)
RETURNS TABLE
AS
RETURN (
    SELECT
        E.ID_EMPRESA,
        E.CEDULA,
        E.NOMBRE_COMERCIAL,
        E.RAZON_SOCIAL,
        E.ID_DIRECCION,
        E.TELEFONO,
        E.CORREO,
        E.FECHA_CREACION,
        E.ACTIVA
    FROM DBO.EMPRESAEMISORA AS E
    WHERE
        E.RAZON_SOCIAL LIKE '%' + @RAZONSOCIAL + '%'
);
GO

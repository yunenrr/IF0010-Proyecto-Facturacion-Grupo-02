DECLARE @CODIGOPRODUCTO INT = 1;
DECLARE @FECHAINICIO DATETIME2 = '2026-10-29 02:15:59.9850128';
DECLARE @FECHAFIN DATETIME2 = '2026-12-30 02:15:59.9850128';

SELECT
    F.CODIGO_FACTURA,
    F.IDENTIFICADOR_COMPROBANTE,
    DF.CANTIDAD,
    F.FECHA_EMISION
FROM DBO.FACTURA AS F
INNER JOIN DBO.DETALLEFACTURA AS DF
    ON F.CODIGO_FACTURA = DF.CODIGO_FACTURA
WHERE
    DF.CODIGO_PRODUCTO = @CODIGOPRODUCTO
    AND F.FECHA_EMISION BETWEEN @FECHAINICIO AND @FECHAFIN;
GO

DECLARE @NOMBRE_BUSCADO VARCHAR(50) = 'Esteban';
DECLARE @APELLIDO1_BUSCADO VARCHAR(50) = 'Aguilar';

SELECT
    ID_CLIENTE,
    CEDULA_CLIENTE,
    NOMBRE,
    PRIMER_APELLIDO,
    SEGUNDO_APELLIDO,
    TELEFONO,
    CORREO,
    FECHA_REGISTRO
FROM DBO.CLIENTE
WHERE
    LEN(REPLACE(CEDULA_CLIENTE, '-', '')) = 9
    AND NOMBRE LIKE '%' + @NOMBRE_BUSCADO + '%'
    AND PRIMER_APELLIDO LIKE '%' + @APELLIDO1_BUSCADO + '%';
GO

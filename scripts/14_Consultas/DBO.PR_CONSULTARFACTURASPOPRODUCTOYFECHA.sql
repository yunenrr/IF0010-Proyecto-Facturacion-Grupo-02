USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'PR_CONSULTARFACTURASPOPRODUCTOYFECHA'
            AND TYPE = 'P'
    )
    BEGIN
        DROP PROCEDURE DBO.PR_CONSULTARFACTURASPOPRODUCTOYFECHA;
    END;
GO

CREATE PROCEDURE DBO.PR_CONSULTARFACTURASPOPRODUCTOYFECHA(
    @CODIGOPRODUCTO INT,
    @FECHAINICIO DATETIME2,
    @FECHAFIN DATETIME2
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        F.CODIGO_FACTURA,
        F.IDENTIFICADOR_COMPROBANTE,
        DF.CANTIDAD,
        F.FECHA_EMISION
    FROM DBO.FACTURA AS F
    INNER JOIN DBO.DETALLEFACTURA AS DF
        ON F.CODIGO_FACTURA = DF.CODIGO_FACTURA
    WHERE
        DF.CODIGO_PRODUCTO = @CODIGOPRODUCTO
        AND F.FECHA_EMISION BETWEEN @FECHAINICIO AND @FECHAFIN;
    END;
    GO
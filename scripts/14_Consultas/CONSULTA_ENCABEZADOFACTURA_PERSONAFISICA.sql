USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

DECLARE @CEDULA VARCHAR(20);

SELECT TOP 1 @CEDULA = C.CEDULA_CLIENTE
FROM DBO.CLIENTE AS C
INNER JOIN DBO.FACTURA AS F
    ON C.ID_CLIENTE = F.ID_CLIENTE
WHERE LEN(REPLACE(C.CEDULA_CLIENTE, '-', '')) = 9
ORDER BY C.ID_CLIENTE;

SELECT
    C.CEDULA_CLIENTE,
    C.NOMBRE AS NOMBRE_CLIENTE,
    F.CODIGO_FACTURA,
    F.IDENTIFICADOR_COMPROBANTE,
    F.FECHA_EMISION,
    F.ID_EMPRESA,
    F.ID_TIPO_DOCUMENTO,
    F.CODIGO_DIVISA,
    F.ID_ESTADO,
    F.SUBTOTAL,
    F.TOTAL_DESCUENTOS,
    F.TOTAL_IMPUESTOS,
    F.MONTO_TOTAL,
    ISNULL(O.OBSERVACION, 'Sin observaciones') AS OBSERVACION
FROM DBO.CLIENTE AS C
INNER JOIN DBO.FACTURA AS F
    ON C.ID_CLIENTE = F.ID_CLIENTE
LEFT JOIN DBO.OBSERVACION_FACTURA AS O
    ON F.CODIGO_FACTURA = O.CODIGO_FACTURA
WHERE
    C.CEDULA_CLIENTE = @CEDULA
    AND LEN(REPLACE(C.CEDULA_CLIENTE, '-', '')) = 9
ORDER BY F.FECHA_EMISION;
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_CLIENTE_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_CLIENTE_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_CLIENTE_AUDITORIA
ON DBO.CLIENTE
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE',
        CAST(I.ID_CLIENTE AS VARCHAR(50)),
        1,
        'REGISTRO',
        'N/A',
        CONCAT(I.CEDULA_CLIENTE, ' | ', I.NOMBRE)
    FROM INSERTED AS I
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE',
        CAST(D.ID_CLIENTE AS VARCHAR(50)),
        3,
        'REGISTRO',
        CONCAT(D.CEDULA_CLIENTE, ' | ', D.NOMBRE),
        'N/A'
    FROM DELETED AS D
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE',
        CAST(I.ID_CLIENTE AS VARCHAR(50)),
        2,
        C.CAMPO,
        C.ANTERIOR,
        C.NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    CROSS APPLY (
        VALUES
            ('NOMBRE', D.NOMBRE, I.NOMBRE),
            ('TELEFONO', D.TELEFONO, I.TELEFONO),
            ('CORREO', D.CORREO, I.CORREO),
            (
                'ID_DIRECCION',
                CAST(D.ID_DIRECCION AS VARCHAR(50)),
                CAST(I.ID_DIRECCION AS VARCHAR(50))
            )
    ) AS C(CAMPO, ANTERIOR, NUEVO)
    WHERE C.ANTERIOR <> C.NUEVO;
END;
GO

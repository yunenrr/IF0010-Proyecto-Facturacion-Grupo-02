USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_DETALLE_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_DETALLE_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_DETALLE_AUDITORIA
ON DBO.DETALLEFACTURA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DETALLEFACTURA' AS TABLA_AFECTADA,
        I.ID_DETALLE AS LLAVE_PRIMARIA,
        1 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        'N/A' AS VALOR_ANTERIOR,
        CONCAT(
            'PRODUCTO: ',
            I.CODIGO_PRODUCTO,
            ' | CANTIDAD: ',
            I.CANTIDAD,
            ' | TOTAL: ',
            I.MONTO_TOTAL_LINEA
        ) AS VALOR_NUEVO
    FROM INSERTED AS I
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM DELETED
        );

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DETALLEFACTURA' AS TABLA_AFECTADA,
        D.ID_DETALLE AS LLAVE_PRIMARIA,
        3 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        CONCAT(
            'PRODUCTO: ',
            D.CODIGO_PRODUCTO,
            ' | CANTIDAD: ',
            D.CANTIDAD,
            ' | TOTAL: ',
            D.MONTO_TOTAL_LINEA
        ) AS VALOR_ANTERIOR,
        'N/A' AS VALOR_NUEVO
    FROM DELETED AS D
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM INSERTED
        );

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DETALLEFACTURA' AS TABLA_AFECTADA,
        I.ID_DETALLE AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'CANTIDAD' AS CAMPO_MODIFICADO,
        CAST(D.CANTIDAD AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.CANTIDAD AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
       AND I.ID_DETALLE = D.ID_DETALLE
    WHERE
        I.CANTIDAD <> D.CANTIDAD;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DETALLEFACTURA' AS TABLA_AFECTADA,
        I.ID_DETALLE AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'PRECIO_UNITARIO' AS CAMPO_MODIFICADO,
        CAST(D.PRECIO_UNITARIO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.PRECIO_UNITARIO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
       AND I.ID_DETALLE = D.ID_DETALLE
    WHERE
        I.PRECIO_UNITARIO <> D.PRECIO_UNITARIO;
    
    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DETALLEFACTURA' AS TABLA_AFECTADA,
        I.ID_DETALLE AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'PORCENTAJE_DESCUENTO' AS CAMPO_MODIFICADO,
        CAST(D.PORCENTAJE_DESCUENTO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.PORCENTAJE_DESCUENTO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
       AND I.ID_DETALLE = D.ID_DETALLE
    WHERE
        I.PORCENTAJE_DESCUENTO <> D.PORCENTAJE_DESCUENTO;
END;
GO

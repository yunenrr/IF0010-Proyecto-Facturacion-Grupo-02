USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_PRODUCTO_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_PRODUCTO_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_PRODUCTO_AUDITORIA
ON DBO.PRODUCTO
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'PRODUCTO' AS TABLA_AFECTADA,
        CAST(I.CODIGO_ID AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        1 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        'N/A' AS VALOR_ANTERIOR,
        CONCAT(I.CODIGO_ID, ' | ', I.DESCRIPCION) AS VALOR_NUEVO
    FROM INSERTED AS I
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM DELETED
        );

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'PRODUCTO' AS TABLA_AFECTADA,
        CAST(D.CODIGO_ID AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        3 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        CONCAT(D.CODIGO_ID, ' | ', D.DESCRIPCION) AS VALOR_ANTERIOR,
        'N/A' AS VALOR_NUEVO
    FROM DELETED AS D
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM INSERTED
        );

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'PRODUCTO' AS TABLA_AFECTADA,
        CAST(I.CODIGO_ID AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'DESCRIPCION' AS CAMPO_MODIFICADO,
        D.DESCRIPCION AS VALOR_ANTERIOR,
        I.DESCRIPCION AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_ID = D.CODIGO_ID
    WHERE I.DESCRIPCION <> D.DESCRIPCION;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'PRODUCTO' AS TABLA_AFECTADA,
        CAST(I.CODIGO_ID AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'PRECIO_UNITARIO' AS CAMPO_MODIFICADO,
        CAST(D.PRECIO_UNITARIO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.PRECIO_UNITARIO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_ID = D.CODIGO_ID
    WHERE I.PRECIO_UNITARIO <> D.PRECIO_UNITARIO;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'PRODUCTO' AS TABLA_AFECTADA,
        CAST(I.CODIGO_ID AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'PORCENTAJE_IMPUESTO' AS CAMPO_MODIFICADO,
        CAST(D.PORCENTAJE_IMPUESTO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.PORCENTAJE_IMPUESTO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_ID = D.CODIGO_ID
    WHERE I.PORCENTAJE_IMPUESTO <> D.PORCENTAJE_IMPUESTO;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'PRODUCTO' AS TABLA_AFECTADA,
        CAST(I.CODIGO_ID AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'STOCK_ACTUAL' AS CAMPO_MODIFICADO,
        CAST(D.STOCK_ACTUAL AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.STOCK_ACTUAL AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_ID = D.CODIGO_ID
    WHERE I.STOCK_ACTUAL <> D.STOCK_ACTUAL;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'PRODUCTO' AS TABLA_AFECTADA,
        CAST(I.CODIGO_ID AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'STOCK_MINIMO' AS CAMPO_MODIFICADO,
        CAST(D.STOCK_MINIMO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.STOCK_MINIMO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_ID = D.CODIGO_ID
    WHERE I.STOCK_MINIMO <> D.STOCK_MINIMO;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'PRODUCTO' AS TABLA_AFECTADA,
        CAST(I.CODIGO_ID AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'ESTADO' AS CAMPO_MODIFICADO,
        CAST(D.ESTADO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.ESTADO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_ID = D.CODIGO_ID
    WHERE I.ESTADO <> D.ESTADO;
END;
GO

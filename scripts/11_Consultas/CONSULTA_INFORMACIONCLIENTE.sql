USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

EXECUTE AS USER = N'USERADMINISTRADOR'; -- noqa: PRS
SELECT
    USER_NAME() AS IDENTIDAD,
    IS_MEMBER(N'ADMINISTRADOR') AS ESADMINISTRADOR;
SELECT TOP 5
    ID_CLIENTE,
    CEDULA_CLIENTE,
    NOMBRE,
    PROVINCIA,
    CANTON,
    DISTRITO,
    SENAS_ADICIONALES,
    FECHA_REGISTRO,
    TELEFONO,
    CORREO
FROM DBO.FN_INFORMACIONCLIENTES()
ORDER BY ID_CLIENTE;
REVERT;


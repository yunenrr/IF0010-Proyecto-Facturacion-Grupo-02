DECLARE @RAZONSOCIAL VARCHAR(150) = '';

SELECT
    E.ID_EMPRESA,
    E.CEDULA,
    E.NOMBRE_COMERCIAL,
    E.RAZON_SOCIAL,
    E.ID_DIRECCION,
    E.TELEFONO,
    E.CORREO,
    E.FECHA_CREACION,
    E.ACTIVA
FROM DBO.EMPRESA_EMISORA AS E
WHERE
    E.RAZON_SOCIAL LIKE '%' + @RAZONSOCIAL + '%';
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

DECLARE @CEDULA VARCHAR(20) = '3101000010';

SELECT
    C.CEDULA,
    CJ.RAZON_SOCIAL,
    CJ.NOMBRE_COMERCIAL,
    F.CODIGO_FACTURA,
    F.IDENTIFICADOR_COMPROBANTE,
    F.FECHA_EMISION,
    TD.DESCRIPCION_TIPO_DOCUMENTO,
    EF.ESTADO,
    F.CODIGO_DIVISA,
    F.SUBTOTAL,
    F.TOTAL_DESCUENTOS,
    F.TOTAL_IMPUESTOS,
    F.MONTO_TOTAL
FROM DBO.CLIENTE AS C
INNER JOIN DBO.CLIENTE_JURIDICO AS CJ
    ON C.ID_CLIENTE = CJ.ID_CLIENTE
INNER JOIN DBO.FACTURA AS F
    ON C.ID_CLIENTE = F.ID_CLIENTE
INNER JOIN DBO.TIPO_DOCUMENTO AS TD
    ON F.ID_TIPO_DOCUMENTO = TD.ID_TIPO_DOCUMENTO
INNER JOIN DBO.ESTADO_FACTURA AS EF
    ON F.ID_ESTADO = EF.ID_ESTADO
WHERE C.CEDULA = @CEDULA
ORDER BY F.FECHA_EMISION DESC;
GO

SELECT TOP 100
    C.CEDULA_CLIENTE,
    C.NOMBRE,
    F.CODIGO_FACTURA,
    F.IDENTIFICADOR_COMPROBANTE,
    F.FECHA_EMISION,
    TD.DESCRIPCION_TIPO_DOCUMENTO,
    EF.ESTADO,
    F.CODIGO_DIVISA,
    F.SUBTOTAL,
    F.TOTAL_DESCUENTOS,
    F.TOTAL_IMPUESTOS,
    F.MONTO_TOTAL
FROM DBO.FACTURA AS F
INNER JOIN DBO.CLIENTE AS C
    ON F.ID_CLIENTE = C.ID_CLIENTE
INNER JOIN DBO.TIPODOCUMENTO AS TD
    ON F.ID_TIPO_DOCUMENTO = TD.ID_TIPO_DOCUMENTO
INNER JOIN DBO.ESTADOFACTURA AS EF
    ON F.ID_ESTADO = EF.ID_ESTADO
WHERE
    C.CEDULA_CLIENTE = '3-101-123456'
    AND LEN(REPLACE(C.CEDULA_CLIENTE, '-', '')) = 10
ORDER BY F.FECHA_EMISION DESC;
GO

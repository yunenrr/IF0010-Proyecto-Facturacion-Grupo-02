USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

DECLARE @CEDULA VARCHAR(20) = '100000001';

SELECT
    C.CEDULA,
    COALESCE(
        CJ.RAZON_SOCIAL,
        CONCAT_WS(
            ' ',
            CF.NOMBRE,
            CF.PRIMER_APELLIDO,
            CF.SEGUNDO_APELLIDO
        )
    ) AS NOMBRE_O_RAZON_SOCIAL,
    COUNT(F.CODIGO_FACTURA) AS CANTIDAD_FACTURAS,
    ISNULL(SUM(F.TOTAL_DESCUENTOS), 0) AS TOTAL_DESCUENTOS,
    ISNULL(SUM(F.TOTAL_IMPUESTOS), 0) AS TOTAL_IMPUESTOS,
    ISNULL(SUM(F.MONTO_TOTAL), 0) AS MONTO_TOTAL_FACTURADO
FROM DBO.CLIENTE AS C
LEFT JOIN DBO.CLIENTE_FISICO AS CF
    ON C.ID_CLIENTE = CF.ID_CLIENTE
LEFT JOIN DBO.CLIENTE_JURIDICO AS CJ
    ON C.ID_CLIENTE = CJ.ID_CLIENTE
LEFT JOIN DBO.FACTURA AS F
    ON
        C.ID_CLIENTE = F.ID_CLIENTE
        AND F.FECHA_EMISION >= DATEFROMPARTS(YEAR(SYSDATETIME()), 1, 1)
        AND F.FECHA_EMISION < DATEFROMPARTS(YEAR(SYSDATETIME()) + 1, 1, 1)
WHERE C.CEDULA = @CEDULA
GROUP BY
    C.CEDULA,
    CJ.RAZON_SOCIAL,
    CF.NOMBRE,
    CF.PRIMER_APELLIDO,
    CF.SEGUNDO_APELLIDO;
GO

DECLARE @NOMBRE_COMERCIAL VARCHAR(150) = 'Comercial';

SELECT
    C.ID_CLIENTE,
    C.CEDULA,
    CJ.RAZON_SOCIAL,
    CJ.NOMBRE_COMERCIAL,
    C.TELEFONO,
    C.CORREO,
    C.FECHA_REGISTRO
FROM DBO.CLIENTE AS C
INNER JOIN DBO.CLIENTE_JURIDICO AS CJ
    ON C.ID_CLIENTE = CJ.ID_CLIENTE
WHERE CJ.NOMBRE_COMERCIAL LIKE '%' + @NOMBRE_COMERCIAL + '%';
GO

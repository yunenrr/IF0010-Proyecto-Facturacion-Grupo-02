DECLARE @NOMBRE_BUSCADO VARCHAR(50) = 'Esteban';
DECLARE @APELLIDO1_BUSCADO VARCHAR(50) = 'Aguilar';

SELECT
    C.ID_CLIENTE,
    C.CEDULA,
    CF.NOMBRE,
    CF.PRIMER_APELLIDO,
    CF.SEGUNDO_APELLIDO,
    C.TELEFONO,
    C.CORREO,
    C.FECHA_REGISTRO
FROM DBO.CLIENTE AS C
INNER JOIN DBO.CLIENTE_FISICO AS CF
    ON C.ID_CLIENTE = CF.ID_CLIENTE
WHERE
    CF.NOMBRE LIKE @NOMBRE_BUSCADO + '%'
    AND CF.PRIMER_APELLIDO LIKE @APELLIDO1_BUSCADO + '%';
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

DECLARE @CEDULA VARCHAR(20) = '100000001';

EXECUTE AS USER = N'USERADMINISTRADOR'; -- noqa: PRS
BEGIN TRY
    SELECT
        ID_CLIENTE,
        CEDULA,
        TIPO_IDENTIFICACION,
        NOMBRE,
        PRIMER_APELLIDO,
        SEGUNDO_APELLIDO,
        RAZON_SOCIAL,
        NOMBRE_COMERCIAL,
        PROVINCIA,
        CANTON,
        DISTRITO,
        SENAS_ADICIONALES,
        FECHA_REGISTRO,
        TELEFONO,
        CORREO,
        USER_NAME() AS IDENTIDAD
    FROM DBO.FN_INFORMACIONCLIENTES(@CEDULA);
END TRY
BEGIN CATCH
    SELECT
        USER_NAME() AS IDENTIDAD,
        'ACCESO DENEGADO' AS ESTADO_PERMISO,
        ERROR_MESSAGE() AS MENSAJE_ERROR;
END CATCH;
REVERT;


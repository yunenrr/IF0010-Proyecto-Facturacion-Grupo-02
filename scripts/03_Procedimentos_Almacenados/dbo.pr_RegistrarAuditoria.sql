USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF OBJECT_ID('DBO.PR_REGISTRARAUDITORIA', 'P') IS NOT NULL
    DROP PROCEDURE DBO.PR_REGISTRARAUDITORIA;
GO

CREATE PROCEDURE DBO.PR_REGISTRARAUDITORIA
    @TABLAAFECTADA VARCHAR(50),
    @LLAVEPRIMARIA VARCHAR(50),
    @OPERACION VARCHAR(10),
    @CAMPOMODIFICADO VARCHAR(50) = NULL,
    @VALORANTERIOR VARCHAR(MAX) = NULL,
    @VALORNUEVO VARCHAR(MAX) = NULL,
    @USUARIO VARCHAR(100) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        SET @OPERACION = UPPER(@OPERACION);

        IF @OPERACION NOT IN ('INSERT', 'UPDATE', 'DELETE')
            BEGIN
                THROW
                50070,
                'La operación especificada no es válida. Debe ser INSERT, UPDATE o DELETE.',
                1;
            END;

        IF @TABLAAFECTADA IS NULL OR TRIM(TRIM(@TABLAAFECTADA)) = ''
            BEGIN
                THROW
                50071,
                'Debe especificar el nombre de la tabla afectada.',
                1;
            END;

        IF @LLAVEPRIMARIA IS NULL OR TRIM(TRIM(@LLAVEPRIMARIA)) = ''
            BEGIN
                THROW 50072, 'Debe especificar el valor.', 1;
            END;

        IF @USUARIO IS NULL OR TRIM(TRIM(@USUARIO)) = ''
            BEGIN
                SET @USUARIO = SUSER_SNAME();
            END;

        INSERT INTO DBO.AUDITORIASISTEMA (
            TABLA_AFECTADA,
            LLAVE_PRIMARIA,
            OPERACION,
            CAMPO_MODIFICADO,
            VALOR_ANTERIOR,
            VALOR_NUEVO,
            USUARIO,
            FECHA_HORA
        )
        VALUES (
            @TABLAAFECTADA,
            @LLAVEPRIMARIA,
            @OPERACION,
            @CAMPOMODIFICADO,
            @VALORANTERIOR,
            @VALORNUEVO,
            @USUARIO,
            SYSDATETIME()
        );

        DECLARE @IDAUDITORIAGENERADO INT = SCOPE_IDENTITY();

        COMMIT TRANSACTION;

        SELECT
            DBO.AUDITORIASISTEMA.ID_AUDITORIA,
            DBO.AUDITORIASISTEMA.TABLA_AFECTADA,
            DBO.AUDITORIASISTEMA.LLAVE_PRIMARIA,
            DBO.AUDITORIASISTEMA.OPERACION,
            DBO.AUDITORIASISTEMA.CAMPO_MODIFICADO,
            DBO.AUDITORIASISTEMA.VALOR_ANTERIOR,
            DBO.AUDITORIASISTEMA.VALOR_NUEVO,
            DBO.AUDITORIASISTEMA.USUARIO,
            DBO.AUDITORIASISTEMA.FECHA_HORA
        FROM DBO.AUDITORIASISTEMA
        WHERE
            DBO.AUDITORIASISTEMA.ID_AUDITORIA = @IDAUDITORIAGENERADO;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            BEGIN
                ROLLBACK TRANSACTION;
            END;

        THROW;
    END CATCH;
END;
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE FACTURA (
    CODIGO_FACTURA INT NOT NULL,
    IDENTIFICADOR_COMPROBANTE VARCHAR(100) NOT NULL,
    ID_EMPRESA INT NOT NULL,
    ID_CLIENTE INT NOT NULL,
    ID_TIPO_DOCUMENTO INT NOT NULL,
    CODIGO_DIVISA CHAR(3) NOT NULL,
    ID_ESTADO INT NOT NULL,
    FECHA_EMISION DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    SUBTOTAL DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    TOTAL_DESCUENTOS DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    TOTAL_IMPUESTOS DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    MONTO_TOTAL DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    CREATED_AT DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UPDATED_AT DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CONSTRAINT PK_FACTURA PRIMARY KEY (CODIGO_FACTURA),
    CONSTRAINT UQ_FACTURA_COMPROBANTE UNIQUE (IDENTIFICADOR_COMPROBANTE),
    CONSTRAINT FK_FACTURA_EMPRESA_EMISORA
    FOREIGN KEY (ID_EMPRESA)
    REFERENCES EMPRESA_EMISORA (ID_EMPRESA),
    CONSTRAINT FK_FACTURA_CLIENTE
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_FACTURA_TIPO_DOCUMENTO
    FOREIGN KEY (ID_TIPO_DOCUMENTO)
    REFERENCES TIPO_DOCUMENTO (ID_TIPO_DOCUMENTO),
    CONSTRAINT FK_FACTURA_DIVISA
    FOREIGN KEY (CODIGO_DIVISA)
    REFERENCES DIVISA (CODIGO_DIVISA),
    CONSTRAINT FK_FACTURA_ESTADO_FACTURA
    FOREIGN KEY (ID_ESTADO)
    REFERENCES ESTADO_FACTURA (ID_ESTADO)
);
GO

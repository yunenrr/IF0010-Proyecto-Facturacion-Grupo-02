CREATE TABLE AUDITORIA_SISTEMA (
    ID_AUDITORIA INT IDENTITY (1, 1) NOT NULL,
    TABLA_AFECTADA VARCHAR(50) NOT NULL,
    LLAVE_PRIMARIA VARCHAR(50) NOT NULL,
    ID_OPERACION INT NOT NULL,
    CAMPO_MODIFICADO VARCHAR(50) NOT NULL DEFAULT 'N/A',
    VALOR_ANTERIOR VARCHAR(MAX) NOT NULL DEFAULT 'N/A',
    VALOR_NUEVO VARCHAR(MAX) NOT NULL DEFAULT 'N/A',
    USUARIO VARCHAR(100) NOT NULL DEFAULT SUSER_SNAME(),
    FECHA_HORA DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CONSTRAINT PK_AUDITORIASISTEMA PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT FK_AUDITORIA_OPERACION
    FOREIGN KEY (ID_OPERACION)
    REFERENCES TIPO_OPERACION (ID_OPERACION)
);
GO

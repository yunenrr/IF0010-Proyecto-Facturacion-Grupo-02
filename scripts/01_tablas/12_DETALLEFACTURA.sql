CREATE TABLE DETALLEFACTURA (
    CODIGO_FACTURA INT NOT NULL,
    ID_DETALLE INT IDENTITY (1, 1) NOT NULL,
    CODIGO_PRODUCTO INT NOT NULL,
    NUMERO_LINEA INT NOT NULL,
    DESCRIPCION VARCHAR(255) NOT NULL,
    CANTIDAD DECIMAL(12, 2) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 2) NOT NULL,
    PORCENTAJE_DESCUENTO DECIMAL(5, 2) NOT NULL DEFAULT 0.00,
    PORCENTAJE_IMPUESTO DECIMAL(5, 2) NOT NULL DEFAULT 0.00,
    SUBTOTAL_LINEA DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    MONTO_DESCUENTO DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    MONTO_IMPUESTO DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    MONTO_TOTAL_LINEA DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT PK_DETALLEFACTURA PRIMARY KEY (CODIGO_FACTURA, ID_DETALLE),
    CONSTRAINT FK_DETALLEFACTURA_FACTURA
    FOREIGN KEY (CODIGO_FACTURA)
    REFERENCES FACTURA (CODIGO_FACTURA)
    ON DELETE CASCADE,
    CONSTRAINT FK_DETALLEFACTURA_PRODUCTO
    FOREIGN KEY (CODIGO_PRODUCTO)
    REFERENCES PRODUCTO (CODIGO_ID)
);
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;

CREATE TABLE EMPRESAEMISORA (
    CEDULA VARCHAR(20) NOT NULL,
    NOMBRE_COMERCIAL VARCHAR(150) NOT NULL,
    RAZON_SOCIAL VARCHAR(150) NOT NULL,
    DIRECCION VARCHAR(250) NULL,
    TELEFONO VARCHAR(20) NULL,
    CORREO VARCHAR(100) NULL,
    FECHA_CREACION DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    ACTIVA BIT NOT NULL DEFAULT 1,
    CONSTRAINT PK_EMPRESAEMISORA
        PRIMARY KEY (CEDULA)
);

CREATE TABLE CLIENTE (
    CEDULA VARCHAR(20) NOT NULL,
    NOMBRE VARCHAR(70) NOT NULL,
    DIRECCION_CONTACTO VARCHAR(50) NOT NULL,
    TELEFONO VARCHAR(15) NOT NULL,
    CORREO VARCHAR(75) NOT NULL,
    FECHA_REGISTRO DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    ULTIMA_ACTUALIZACION DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CONSTRAINT PK_CLIENTE
        PRIMARY KEY (CEDULA)
);

CREATE TABLE TIPODOCUMENTO (
    ID_TIPO_DOCUMENTO INT NOT NULL,
    DESCRIPCION_TIPO_DOCUMENTO VARCHAR(50) NOT NULL,
    CONSTRAINT PK_TIPODOCUMENTO
        PRIMARY KEY (ID_TIPO_DOCUMENTO)
);

CREATE TABLE DIVISA (
    CODIGO_DIVISA CHAR(3) NOT NULL,
    NOMBRE VARCHAR(50) NOT NULL,
    SIMBOLO VARCHAR(5) NOT NULL,
    CONSTRAINT PK_DIVISA
        PRIMARY KEY (CODIGO_DIVISA)
);

CREATE TABLE ESTADOFACTURA (
    ESTADO VARCHAR(20) NOT NULL,
    DESCRIPCION_ESTADO VARCHAR(100) NOT NULL,
    CONSTRAINT PK_ESTADOFACTURA
        PRIMARY KEY (ESTADO)
);

CREATE TABLE PRODUCTOSERVICIO (
    CODIGO_ID VARCHAR(30) NOT NULL,
    DESCRIPCION VARCHAR(255) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 2) NOT NULL,
    PORCENTAJE_IMPUESTO DECIMAL(5, 2) NOT NULL,
    TIPO_ITEM VARCHAR(10) NOT NULL DEFAULT 'PRODUCTO',
    ESTADO VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CONSTRAINT PK_PRODUCTOSERVICIO
        PRIMARY KEY (CODIGO_ID)
);

CREATE TABLE FACTURA (
    CODIGO_FACTURA INT IDENTITY (1, 1) NOT NULL,
    IDENTIFICADOR_COMPROBANTE VARCHAR(30) NOT NULL,
    CEDULA_EMPRESA VARCHAR(20) NOT NULL,
    CEDULA_CLIENTE VARCHAR(20) NOT NULL,
    ID_TIPO_DOCUMENTO INT NOT NULL,
    CODIGO_DIVISA CHAR(3) NOT NULL,
    ESTADO_FACTURA VARCHAR(20) NOT NULL DEFAULT 'EMITIDA',
    FECHA_EMISION DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    SUBTOTAL DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    TOTAL_DESCUENTOS DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    TOTAL_IMPUESTOS DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    MONTO_TOTAL AS (SUBTOTAL - TOTAL_DESCUENTOS + TOTAL_IMPUESTOS) PERSISTED,
    OBSERVACIONES VARCHAR(255) NULL,
    CREATED_AT DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UPDATED_AT DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CONSTRAINT PK_FACTURA
        PRIMARY KEY (CODIGO_FACTURA),
    CONSTRAINT UQ_FACTURA_COMPROBANTE
        UNIQUE (IDENTIFICADOR_COMPROBANTE),
    CONSTRAINT FK_FACTURA_EMPRESAEM
        FOREIGN KEY (CEDULA_EMPRESA) REFERENCES EMPRESAEMISORA (CEDULA),
    CONSTRAINT FK_FACTURA_CLIENTE
        FOREIGN KEY (CEDULA_CLIENTE) REFERENCES CLIENTE (CEDULA),
    CONSTRAINT FK_FACTURA_TIPODOC
        FOREIGN KEY (ID_TIPO_DOCUMENTO)
        REFERENCES TIPODOCUMENTO (ID_TIPO_DOCUMENTO),
    CONSTRAINT FK_FACTURA_DIVISA
        FOREIGN KEY (CODIGO_DIVISA) REFERENCES DIVISA (CODIGO_DIVISA),
    CONSTRAINT FK_FACTURA_ESTADO
        FOREIGN KEY (ESTADO_FACTURA) REFERENCES ESTADOFACTURA (ESTADO)
);

CREATE TABLE DETALLEFACTURA (
    ID_DETALLE INT IDENTITY (1, 1) NOT NULL,
    CODIGO_FACTURA INT NOT NULL,
    CODIGO_PRODUCTO VARCHAR(30) NOT NULL,
    NUMERO_LINEA INT NOT NULL,
    DESCRIPCION VARCHAR(255) NOT NULL,
    CANTIDAD DECIMAL(12, 2) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 2) NOT NULL,
    PORCENTAJE_DESCUENTO DECIMAL(5, 2) NOT NULL DEFAULT 0.00,
    PORCENTAJE_IMPUESTO DECIMAL(5, 2) NOT NULL DEFAULT 0.00,
    SUBTOTAL_LINEA AS (CANTIDAD * PRECIO_UNITARIO) PERSISTED,
    MONTO_DESCUENTO AS (
        CANTIDAD * PRECIO_UNITARIO * (PORCENTAJE_DESCUENTO / 100.0)
    ) PERSISTED,
    MONTO_IMPUESTO AS (
        (
            CANTIDAD * PRECIO_UNITARIO
            - (CANTIDAD * PRECIO_UNITARIO * (PORCENTAJE_DESCUENTO / 100.0))
        ) * (PORCENTAJE_IMPUESTO / 100.0)
    ) PERSISTED,
    MONTO_TOTAL_LINEA AS (
        (
            CANTIDAD * PRECIO_UNITARIO
            - (CANTIDAD * PRECIO_UNITARIO * (PORCENTAJE_DESCUENTO / 100.0))
        ) + (
            (
                CANTIDAD * PRECIO_UNITARIO
                - (
                    CANTIDAD * PRECIO_UNITARIO
                    * (PORCENTAJE_DESCUENTO / 100.0)
                )
            ) * (PORCENTAJE_IMPUESTO / 100.0)
        )
    ) PERSISTED,
    CONSTRAINT PK_DETALLEFACTURA
        PRIMARY KEY (ID_DETALLE),
    CONSTRAINT FK_DETALLEFACTURA_FACTURA
        FOREIGN KEY (CODIGO_FACTURA) REFERENCES FACTURA (CODIGO_FACTURA)
        ON DELETE CASCADE,
    CONSTRAINT FK_DETALLEFACTURA_PRODUCTO
        FOREIGN KEY (CODIGO_PRODUCTO) REFERENCES PRODUCTOSERVICIO (CODIGO_ID)
);

CREATE TABLE AUDITORIASISTEMA (
    ID_AUDITORIA INT IDENTITY (1, 1) NOT NULL,
    TABLA_AFECTADA VARCHAR(50) NOT NULL,
    LLAVE_PRIMARIA VARCHAR(50) NOT NULL,
    OPERACION VARCHAR(10) NOT NULL,
    CAMPO_MODIFICADO VARCHAR(50) NULL,
    VALOR_ANTERIOR VARCHAR(MAX) NULL,
    VALOR_NUEVO VARCHAR(MAX) NULL,
    USUARIO VARCHAR(100) NOT NULL DEFAULT SUSER_SNAME(),
    FECHA_HORA DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CONSTRAINT PK_AUDITORIASISTEMA
        PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT CHK_AUDITORIA_OPERACION
        CHECK (OPERACION IN ('INSERT', 'UPDATE', 'DELETE'))
);

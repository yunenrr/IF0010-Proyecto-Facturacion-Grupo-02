USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_OBSERVACION_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_OBSERVACION_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_OBSERVACION_AUDITORIA
ON DBO.OBSERVACION_FACTURA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'OBSERVACION_FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        1 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        'N/A' AS VALOR_ANTERIOR,
        I.OBSERVACION AS VALOR_NUEVO
    FROM INSERTED AS I
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM DELETED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'OBSERVACION_FACTURA' AS TABLA_AFECTADA,
        CAST(D.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        3 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        D.OBSERVACION AS VALOR_ANTERIOR,
        'N/A' AS VALOR_NUEVO
    FROM DELETED AS D
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM INSERTED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'OBSERVACION_FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'OBSERVACION' AS CAMPO_MODIFICADO,
        D.OBSERVACION AS VALOR_ANTERIOR,
        I.OBSERVACION AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.OBSERVACION <> D.OBSERVACION;
END;
GO

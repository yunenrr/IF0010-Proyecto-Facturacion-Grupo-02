USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_CLIENTE_FISICO_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_CLIENTE_FISICO_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_CLIENTE_FISICO_AUDITORIA
ON DBO.CLIENTE_FISICO
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_FISICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        1 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        'N/A' AS VALOR_ANTERIOR,
        CONCAT_WS(
            ' ',
            I.NOMBRE,
            I.PRIMER_APELLIDO,
            I.SEGUNDO_APELLIDO
        ) AS VALOR_NUEVO
    FROM INSERTED AS I
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM DELETED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_FISICO' AS TABLA_AFECTADA,
        CAST(D.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        3 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        CONCAT_WS(
            ' ',
            D.NOMBRE,
            D.PRIMER_APELLIDO,
            D.SEGUNDO_APELLIDO
        ) AS VALOR_ANTERIOR,
        'N/A' AS VALOR_NUEVO
    FROM DELETED AS D
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM INSERTED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_FISICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'NOMBRE' AS CAMPO_MODIFICADO,
        D.NOMBRE AS VALOR_ANTERIOR,
        I.NOMBRE AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE I.NOMBRE <> D.NOMBRE;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_FISICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'PRIMER_APELLIDO' AS CAMPO_MODIFICADO,
        D.PRIMER_APELLIDO AS VALOR_ANTERIOR,
        I.PRIMER_APELLIDO AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE I.PRIMER_APELLIDO <> D.PRIMER_APELLIDO;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_FISICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'SEGUNDO_APELLIDO' AS CAMPO_MODIFICADO,
        D.SEGUNDO_APELLIDO AS VALOR_ANTERIOR,
        I.SEGUNDO_APELLIDO AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE I.SEGUNDO_APELLIDO <> D.SEGUNDO_APELLIDO;
END;
GO

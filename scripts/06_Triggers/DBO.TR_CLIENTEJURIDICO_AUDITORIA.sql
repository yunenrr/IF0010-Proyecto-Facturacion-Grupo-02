USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_CLIENTE_JURIDICO_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_CLIENTE_JURIDICO_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_CLIENTE_JURIDICO_AUDITORIA
ON DBO.CLIENTE_JURIDICO
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_JURIDICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        1 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        'N/A' AS VALOR_ANTERIOR,
        CONCAT(I.RAZON_SOCIAL, ' | ', I.NOMBRE_COMERCIAL) AS VALOR_NUEVO
    FROM INSERTED AS I
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM DELETED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_JURIDICO' AS TABLA_AFECTADA,
        CAST(D.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        3 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        CONCAT(D.RAZON_SOCIAL, ' | ', D.NOMBRE_COMERCIAL) AS VALOR_ANTERIOR,
        'N/A' AS VALOR_NUEVO
    FROM DELETED AS D
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM INSERTED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_JURIDICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'RAZON_SOCIAL' AS CAMPO_MODIFICADO,
        D.RAZON_SOCIAL AS VALOR_ANTERIOR,
        I.RAZON_SOCIAL AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE I.RAZON_SOCIAL <> D.RAZON_SOCIAL;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE_JURIDICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'NOMBRE_COMERCIAL' AS CAMPO_MODIFICADO,
        D.NOMBRE_COMERCIAL AS VALOR_ANTERIOR,
        I.NOMBRE_COMERCIAL AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE I.NOMBRE_COMERCIAL <> D.NOMBRE_COMERCIAL;
END;
GO

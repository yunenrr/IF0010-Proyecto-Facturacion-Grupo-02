USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_CLIENTEJURIDICO_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_CLIENTEJURIDICO_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_CLIENTEJURIDICO_AUDITORIA
ON DBO.CLIENTE
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE JURIDICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        1 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        'N/A' AS VALOR_ANTERIOR,
        CONCAT(I.CEDULA_CLIENTE, ' | ', I.NOMBRE) AS VALOR_NUEVO
    FROM INSERTED AS I
    WHERE
        LEN(REPLACE(I.CEDULA_CLIENTE, '-', '')) = 10
        AND NOT EXISTS (
            SELECT 1
            FROM DELETED
        );

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE JURIDICO' AS TABLA_AFECTADA,
        CAST(D.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        3 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        CONCAT(D.CEDULA_CLIENTE, ' | ', D.NOMBRE) AS VALOR_ANTERIOR,
        'N/A' AS VALOR_NUEVO
    FROM DELETED AS D
    WHERE
        LEN(REPLACE(D.CEDULA_CLIENTE, '-', '')) = 10
        AND NOT EXISTS (
            SELECT 1
            FROM INSERTED
        );

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE JURIDICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'NOMBRE' AS CAMPO_MODIFICADO,
        D.NOMBRE AS VALOR_ANTERIOR,
        I.NOMBRE AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE
        LEN(REPLACE(I.CEDULA_CLIENTE, '-', '')) = 10
        AND I.NOMBRE <> D.NOMBRE;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE JURIDICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'TELEFONO' AS CAMPO_MODIFICADO,
        D.TELEFONO AS VALOR_ANTERIOR,
        I.TELEFONO AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE
        LEN(REPLACE(I.CEDULA_CLIENTE, '-', '')) = 10
        AND I.TELEFONO <> D.TELEFONO;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE JURIDICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'CORREO' AS CAMPO_MODIFICADO,
        D.CORREO AS VALOR_ANTERIOR,
        I.CORREO AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE
        LEN(REPLACE(I.CEDULA_CLIENTE, '-', '')) = 10
        AND I.CORREO <> D.CORREO;

    INSERT INTO DBO.AUDITORIASISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'CLIENTE JURIDICO' AS TABLA_AFECTADA,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'ID_DIRECCION' AS CAMPO_MODIFICADO,
        CAST(D.ID_DIRECCION AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.ID_DIRECCION AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_CLIENTE = D.ID_CLIENTE
    WHERE
        LEN(REPLACE(I.CEDULA_CLIENTE, '-', '')) = 10
        AND I.ID_DIRECCION <> D.ID_DIRECCION;
END;
GO

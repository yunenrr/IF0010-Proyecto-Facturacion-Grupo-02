USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_DIRECCION_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_DIRECCION_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_DIRECCION_AUDITORIA
ON DBO.DIRECCION
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DIRECCION' AS TABLA_AFECTADA,
        CAST(I.ID_DIRECCION AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        1 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        'N/A' AS VALOR_ANTERIOR,
        CONCAT(
            'DISTRITO: ',
            I.ID_DISTRITO,
            ' | Señas: ',
            I.SENAS_ADICIONALES
        ) AS VALOR_NUEVO
    FROM INSERTED AS I
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM DELETED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DIRECCION' AS TABLA_AFECTADA,
        CAST(D.ID_DIRECCION AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        3 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        CONCAT(
            'DISTRITO: ',
            D.ID_DISTRITO,
            ' | Señas: ',
            D.SENAS_ADICIONALES
        ) AS VALOR_ANTERIOR,
        'N/A' AS VALOR_NUEVO
    FROM DELETED AS D
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM INSERTED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DIRECCION' AS TABLA_AFECTADA,
        CAST(I.ID_DIRECCION AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'ID_DISTRITO' AS CAMPO_MODIFICADO,
        CAST(D.ID_DISTRITO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.ID_DISTRITO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_DIRECCION = D.ID_DIRECCION
    WHERE
        I.ID_DISTRITO <> D.ID_DISTRITO;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'DIRECCION' AS TABLA_AFECTADA,
        CAST(I.ID_DIRECCION AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'SENAS_ADICIONALES' AS CAMPO_MODIFICADO,
        D.SENAS_ADICIONALES AS VALOR_ANTERIOR,
        I.SENAS_ADICIONALES AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.ID_DIRECCION = D.ID_DIRECCION
    WHERE
        I.SENAS_ADICIONALES <> D.SENAS_ADICIONALES;

END;
GO

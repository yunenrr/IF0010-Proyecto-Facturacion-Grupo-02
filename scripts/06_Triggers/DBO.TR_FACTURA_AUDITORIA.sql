USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'TR_FACTURA_AUDITORIA'
            AND TYPE = 'TR'
    )
    BEGIN
        DROP TRIGGER DBO.TR_FACTURA_AUDITORIA;
    END;
GO

CREATE TRIGGER DBO.TR_FACTURA_AUDITORIA
ON DBO.FACTURA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        1 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        'N/A' AS VALOR_ANTERIOR,
        I.IDENTIFICADOR_COMPROBANTE AS VALOR_NUEVO
    FROM INSERTED AS I
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM DELETED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(D.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        3 AS ID_OPERACION,
        'REGISTRO' AS CAMPO_MODIFICADO,
        D.IDENTIFICADOR_COMPROBANTE AS VALOR_ANTERIOR,
        'N/A' AS VALOR_NUEVO
    FROM DELETED AS D
    WHERE
        NOT EXISTS (
            SELECT 1
            FROM INSERTED
        );

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'ID_ESTADO' AS CAMPO_MODIFICADO,
        CAST(D.ID_ESTADO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.ID_ESTADO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.ID_ESTADO <> D.ID_ESTADO;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'ID_EMPRESA' AS CAMPO_MODIFICADO,
        CAST(D.ID_EMPRESA AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.ID_EMPRESA AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.ID_EMPRESA <> D.ID_EMPRESA;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'ID_CLIENTE' AS CAMPO_MODIFICADO,
        CAST(D.ID_CLIENTE AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.ID_CLIENTE AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.ID_CLIENTE <> D.ID_CLIENTE;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'ID_TIPO_DOCUMENTO' AS CAMPO_MODIFICADO,
        CAST(D.ID_TIPO_DOCUMENTO AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.ID_TIPO_DOCUMENTO AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.ID_TIPO_DOCUMENTO <> D.ID_TIPO_DOCUMENTO;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'CODIGO_DIVISA' AS CAMPO_MODIFICADO,
        D.CODIGO_DIVISA AS VALOR_ANTERIOR,
        I.CODIGO_DIVISA AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.CODIGO_DIVISA <> D.CODIGO_DIVISA;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'SUBTOTAL' AS CAMPO_MODIFICADO,
        CAST(D.SUBTOTAL AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.SUBTOTAL AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.SUBTOTAL <> D.SUBTOTAL;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'TOTAL_DESCUENTOS' AS CAMPO_MODIFICADO,
        CAST(D.TOTAL_DESCUENTOS AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.TOTAL_DESCUENTOS AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.TOTAL_DESCUENTOS <> D.TOTAL_DESCUENTOS;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'TOTAL_IMPUESTOS' AS CAMPO_MODIFICADO,
        CAST(D.TOTAL_IMPUESTOS AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.TOTAL_IMPUESTOS AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.TOTAL_IMPUESTOS <> D.TOTAL_IMPUESTOS;

    INSERT INTO DBO.AUDITORIA_SISTEMA (
        TABLA_AFECTADA,
        LLAVE_PRIMARIA,
        ID_OPERACION,
        CAMPO_MODIFICADO,
        VALOR_ANTERIOR,
        VALOR_NUEVO
    )
    SELECT
        'FACTURA' AS TABLA_AFECTADA,
        CAST(I.CODIGO_FACTURA AS VARCHAR(50)) AS LLAVE_PRIMARIA,
        2 AS ID_OPERACION,
        'MONTO_TOTAL' AS CAMPO_MODIFICADO,
        CAST(D.MONTO_TOTAL AS VARCHAR(50)) AS VALOR_ANTERIOR,
        CAST(I.MONTO_TOTAL AS VARCHAR(50)) AS VALOR_NUEVO
    FROM INSERTED AS I
    INNER JOIN DELETED AS D
        ON I.CODIGO_FACTURA = D.CODIGO_FACTURA
    WHERE I.MONTO_TOTAL <> D.MONTO_TOTAL;
END;
GO

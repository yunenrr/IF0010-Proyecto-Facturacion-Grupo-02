USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_GENERARCLAVECOMPROBANTE'
            AND TYPE = 'FN'
    )
    BEGIN
        DROP FUNCTION DBO.FN_GENERARCLAVECOMPROBANTE;
    END;
GO

CREATE FUNCTION DBO.FN_GENERARCLAVECOMPROBANTE(
    @FECHA DATETIME2,
    @IDTIPODOCUMENTO INT
)
RETURNS VARCHAR(100)
AS
BEGIN
    DECLARE @TIPO VARCHAR(50);
    DECLARE @CLAVE VARCHAR(100);

    SELECT @TIPO = DESCRIPCION_TIPO_DOCUMENTO
    FROM DBO.TIPO_DOCUMENTO
    WHERE ID_TIPO_DOCUMENTO = @IDTIPODOCUMENTO;

    SET @CLAVE = CONCAT(
        CONVERT(VARCHAR(8), @FECHA, 112),
        REPLACE(CONVERT(VARCHAR(8), @FECHA, 108), ':', ''),
        '-',
        @TIPO
    );

    RETURN @CLAVE;
END;
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = N'FN_ESFACTURABORRADOR'
            AND TYPE = 'FN'
    )
    BEGIN
        DROP FUNCTION DBO.FN_ESFACTURABORRADOR;
    END;
GO

CREATE FUNCTION DBO.FN_ESFACTURABORRADOR(
    @IDENTIFICADORCOMPROBANTE VARCHAR(100)
)
RETURNS BIT
AS
BEGIN
    DECLARE @IDESTADO INT;
    DECLARE @ESBORRADOR BIT;

    SELECT @IDESTADO = ID_ESTADO
    FROM DBO.FACTURA
    WHERE IDENTIFICADOR_COMPROBANTE = @IDENTIFICADORCOMPROBANTE;

    IF @IDESTADO = 1
        BEGIN
            SET @ESBORRADOR = 1;
        END;
    ELSE
        BEGIN
            SET @ESBORRADOR = 0;
        END;

    RETURN @ESBORRADOR;
END;
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = N'FN_CONSULTARHISTORIALCAMBIOS'
            AND TYPE = 'IF'
    )
    BEGIN
        DROP FUNCTION DBO.FN_CONSULTARHISTORIALCAMBIOS;
    END;
GO

CREATE FUNCTION DBO.FN_CONSULTARHISTORIALCAMBIOS()
RETURNS TABLE
AS
RETURN (
    SELECT
        A.ID_AUDITORIA,
        A.TABLA_AFECTADA,
        A.LLAVE_PRIMARIA,
        A.ID_OPERACION,
        A.CAMPO_MODIFICADO,
        A.VALOR_ANTERIOR,
        A.VALOR_NUEVO,
        A.USUARIO,
        A.FECHA_HORA
    FROM DBO.AUDITORIASISTEMA AS A
    WHERE
        IS_MEMBER(N'AUDITOR') = 1
        OR IS_MEMBER(N'DBA') = 1
);
GO

USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = N'FN_CALCULARMONTOFINAL'
            AND TYPE = 'FN'
    )
    BEGIN
        DROP FUNCTION DBO.FN_CALCULARMONTOFINAL;
    END;
GO

CREATE FUNCTION DBO.FN_CALCULARMONTOFINAL(
    @CODIGOFACTURA INT
)
RETURNS DECIMAL(18, 2)
AS
BEGIN
    DECLARE @MONTOFINAL DECIMAL(18, 2);

    SELECT @MONTOFINAL = (SUBTOTAL - TOTAL_DESCUENTOS + TOTAL_IMPUESTOS)
    FROM DBO.FACTURA
    WHERE CODIGO_FACTURA = @CODIGOFACTURA;

    RETURN @MONTOFINAL;
END;
GO
